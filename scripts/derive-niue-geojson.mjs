import { writeFile, mkdir } from "node:fs/promises";

const SOURCE =
  "https://upload.wikimedia.org/wikipedia/commons/a/a4/Niue_location_map.svg";

const villages = [
  ["Alofi North", 187],
  ["Alofi South", 423],
  ["Avatele", 128],
  ["Hakupu", 180],
  ["Hikutavake", 39],
  ["Lakepa", 95],
  ["Liku", 74],
  ["Makefu", 73],
  ["Mutalau", 77],
  ["Namukulu", 9],
  ["Tamakautoga", 180],
  ["Toi", 32],
  ["Tuapa", 103],
  ["Vaiea", 81],
];

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`Map download failed: ${response.status}`);
const svg = await response.text();
const areaBlock = svg.match(/<g id="Areas"[^>]*>([\s\S]*?)<\/g>/)?.[1];
if (!areaBlock) throw new Error("Areas group not found");
const paths = [...areaBlock.matchAll(/<path[^>]*d="([\s\S]*?)"[^>]*>/g)].map((m) =>
  m[1].replace(/\s+/g, " ").trim(),
);
if (paths.length !== villages.length) {
  throw new Error(`Expected 14 paths; found ${paths.length}`);
}

const tokenise = (d) =>
  d.match(/[MLHVZmlhvz]|[-+]?(?:\d*\.\d+|\d+\.?)(?:e[-+]?\d+)?/g) ?? [];

function ringsFromPath(d) {
  const t = tokenise(d);
  let i = 0;
  let command = "";
  let x = 0;
  let y = 0;
  let start = [0, 0];
  let ring = [];
  const rings = [];

  const flush = () => {
    if (ring.length > 2) {
      const [fx, fy] = ring[0];
      const [lx, ly] = ring[ring.length - 1];
      if (fx !== lx || fy !== ly) ring.push([fx, fy]);
      rings.push(ring);
    }
    ring = [];
  };

  const add = (nx, ny) => {
    x = nx;
    y = ny;
    ring.push([x, y + 492]);
  };

  while (i < t.length) {
    if (/^[A-Za-z]$/.test(t[i])) command = t[i++];
    if (command === "M" || command === "m") {
      flush();
      const relative = command === "m";
      const nx = Number(t[i++]);
      const ny = Number(t[i++]);
      add(relative ? x + nx : nx, relative ? y + ny : ny);
      start = [x, y];
      command = relative ? "l" : "L";
    } else if (command === "L" || command === "l") {
      const relative = command === "l";
      const nx = Number(t[i++]);
      const ny = Number(t[i++]);
      add(relative ? x + nx : nx, relative ? y + ny : ny);
    } else if (command === "H" || command === "h") {
      const v = Number(t[i++]);
      add(command === "h" ? x + v : v, y);
    } else if (command === "V" || command === "v") {
      const v = Number(t[i++]);
      add(x, command === "v" ? y + v : v);
    } else if (command === "Z" || command === "z") {
      add(start[0], start[1]);
      flush();
      command = "";
    } else {
      throw new Error(`Unsupported command near token ${i}: ${command}`);
    }
  }
  flush();
  return rings;
}

const project = ([x, y]) => [
  Number((-169.975 + (x / 690) * 0.217).toFixed(6)),
  Number((-18.938 - (y / 773) * 0.23).toFixed(6)),
];

const features = paths.map((path, index) => {
  const rings = ringsFromPath(path);
  return {
    type: "Feature",
    properties: {
      name: villages[index][0],
      census_night_population_2022: villages[index][1],
      source_geometry: SOURCE,
      source_population:
        "https://niuestatistics.nu/census/population-housing/",
      processing:
        "Village boundaries converted from a CC BY-SA location-map SVG to WGS84 using the map's published geographic limits.",
    },
    geometry: {
      type: "MultiPolygon",
      coordinates: rings.map((ring) => [ring.map(project)]),
    },
  };
});

const geojson = {
  type: "FeatureCollection",
  name: "Niue village boundaries",
  license: "CC BY-SA 2.0 for derived geometry; census data attributed to Statistics Niue",
  source: SOURCE,
  features,
};

await mkdir(new URL("../data/", import.meta.url), { recursive: true });
await writeFile(
  new URL("../data/niue-villages.geojson", import.meta.url),
  `${JSON.stringify(geojson, null, 2)}\n`,
);
await writeFile(
  new URL("../app/map-data.ts", import.meta.url),
  `// Generated by scripts/derive-niue-geojson.mjs\nexport const VILLAGES = ${JSON.stringify(
    paths.map((path, index) => ({
      name: villages[index][0],
      population: villages[index][1],
      path,
    })),
    null,
    2,
  )} as const;\n`,
);

